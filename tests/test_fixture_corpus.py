"""The committed fixture corpus: synthetic, reproducible, and still wide enough.

`tests/data` is the only corpus the suite has. Every file except the retained
``Trouble_in_Mind_Blues.musicxml`` is generated by ``tests/fixture_scores.py``;
this module holds the two properties that keep that true: no retired
transcription may return, and every generated byte must still be what the
generator says it is.

The feature matrix at the bottom is the reason the corpus exists. It names the
structural facts the tests lean on - the simple metres, two pickup spellings, a
repeat, a triplet lattice, a TAB part, a chords-only head, an `NC` bar and the
three grouped metres (5/4, 7/4, 12/8) - so a fixture regenerated into something
tidier fails here rather than quietly retiring a witness three modules away.
"""

from __future__ import annotations

import os
import unittest
import zipfile
from fractions import Fraction
from functools import reduce
from math import gcd
from xml.etree import ElementTree

from headxml import arrange_xml_head, load_musicxml
from tabscore import score_events, substitute_steps
from tests import fixture_scores
from tests.support import (
    BLUE_MOON,
    CHORDS_ONLY,
    COMMON_8,
    DATA,
    FIVE_FOUR,
    I_WAS_DOING_ALL_RIGHT,
    MISTY,
    RAINY_DAY,
    SEVEN_FOUR,
    TENOR_MADNESS,
    TROUBLE_IN_MIND,
    TWELVE_EIGHT,
    WALTZ,
)

#: The files the repository deliberately does not generate.
RETAINED = {"Trouble_in_Mind_Blues.musicxml"}

#: Names from the retired corpus. None may be committed again.
RETIRED = {
    "All_the_Things_You_Are.musicxml",
    "Blue_Moon.musicxml",
    "Misty.musicxml",
    "The_Jitterbug_Waltz.musicxml",
    "but_not_for_me.mxl",
    "heres_that_rainy_day.musicxml",
    "i_was_doing_all_right.mxl",
    "lead_sheet_chords_only.musicxml",
    "tenor_madness.musicxml",
}


class TestTheCorpusIsSynthetic(unittest.TestCase):
    """Every committed file is the generator's, except the one retained score."""

    def _scores(self):
        return {
            name
            for name in os.listdir(DATA)
            if name.endswith((".musicxml", ".mxl"))
        }

    def test_no_retired_transcription_is_committed(self):
        self.assertEqual(self._scores() & RETIRED, set(), "a retired score came back")

    def test_the_corpus_is_the_retained_score_plus_the_generator(self):
        self.assertEqual(self._scores(), set(fixture_scores.documents()) | RETAINED)

    def test_every_generated_file_matches_the_generator(self):
        """A fixture edited by hand is a second source for one document."""
        for name, expected in fixture_scores.documents().items():
            with self.subTest(fixture=name):
                with open(os.path.join(DATA, name), "rb") as committed:
                    self.assertEqual(committed.read(), expected, name)


#: The quarter-note value of each MusicXML note type this generator writes.
TYPE_QUARTERS = {
    "whole": Fraction(4),
    "half": Fraction(2),
    "quarter": Fraction(1),
    "eighth": Fraction(1, 2),
    "16th": Fraction(1, 4),
    "32nd": Fraction(1, 8),
    "64th": Fraction(1, 16),
}


def score_xml(name: str) -> ElementTree.Element:
    """The document inside a generated fixture, container or plain XML."""
    path = os.path.join(DATA, name)
    if name.endswith(".mxl"):
        with zipfile.ZipFile(path) as archive:
            member = name[: -len(".mxl")] + ".xml"
            text = archive.read(member).decode("utf-8")
    else:
        with open(path, encoding="utf-8") as stream:
            text = stream.read()
    return ElementTree.fromstring(text)


class TestEveryNoteStatesItsWrittenValue(unittest.TestCase):
    """A notation program lays a note out from `<type>`, not from `<duration>`.

    MuseScore reports an incomplete bar when an eighth is written without a
    `<type>`, because it falls back to a quarter notehead and the bar then
    overruns.  music21 sums `<duration>` and cannot see the bug, so this checks
    the two facts against each other: the type (and its dots) is the nominal
    value, and the duration is that value shortened by the tuplet ratio.
    """

    def test_every_note_and_rest_has_a_type_that_matches_its_duration(self):
        for name in fixture_scores.documents():
            score = score_xml(name)
            for part in score.findall("part"):
                measures = part.findall("measure")
                divisions = int(measures[0].findtext("attributes/divisions") or 0)
                self.assertGreater(divisions, 0, name)
                for measure in measures:
                    for note in measure.findall("note"):
                        with self.subTest(fixture=name, measure=measure.get("number")):
                            self._check_note(note, divisions)

    def _check_note(self, note: ElementTree.Element, divisions: int) -> None:
        kind = (note.findtext("type") or "").strip()
        self.assertIn(kind, TYPE_QUARTERS, "a note has no usable <type>")
        dots = len(note.findall("dot"))
        nominal = TYPE_QUARTERS[kind]
        if dots == 1:
            nominal *= Fraction(3, 2)
        else:
            self.assertEqual(dots, 0, "the generator writes at most one dot")
        actual = int(note.findtext("time-modification/actual-notes") or 1)
        normal = int(note.findtext("time-modification/normal-notes") or 1)
        sounding = nominal * Fraction(normal, actual)
        self.assertEqual(
            int(note.findtext("duration") or -1),
            sounding * divisions,
            f"{kind} with {actual}:{normal} does not match its duration",
        )


class TestEveryFullMeasureHasItsMetresWorth(unittest.TestCase):
    """A full bar adds up to its time signature, so a notation program can open it.

    Pickup bars are the named exception: they carry `implicit="yes"` and are
    deliberately short.  A bar with no note at all is incomplete too, which is
    why the melody-less bars carry a whole-measure rest rather than nothing.
    """

    def test_every_non_pickup_measure_is_complete(self):
        for name in fixture_scores.documents():
            score = score_xml(name)
            for part in score.findall("part"):
                measures = part.findall("measure")
                attributes = measures[0].find("attributes")
                assert attributes is not None
                divisions = int(attributes.findtext("divisions") or 0)
                beats = int(attributes.findtext("time/beats") or 0)
                beat_type = int(attributes.findtext("time/beat-type") or 0)
                expected = Fraction(beats * 4, beat_type) * divisions
                for measure in measures:
                    if measure.get("implicit") == "yes":
                        continue
                    with self.subTest(fixture=name, measure=measure.get("number")):
                        total = sum(
                            int(note.findtext("duration") or 0)
                            for note in measure.findall("note")
                            if note.find("chord") is None
                        )
                        self.assertEqual(total, expected)


class TestTheFeatureMatrixSurvives(unittest.TestCase):
    """The structural facts the importer and arrangement tests are built on."""

    def test_the_three_simple_metres_are_committed(self):
        metres = {
            (load_musicxml(path).beats_per_bar, load_musicxml(path).beat_type)
            for path in (COMMON_8, RAINY_DAY, WALTZ)
        }
        self.assertEqual(metres, {(4, 4), (2, 2), (3, 4)})

    def test_both_pickup_spellings_are_committed(self):
        for path in (BLUE_MOON, MISTY):
            with self.subTest(fixture=os.path.basename(path)):
                steps, head, _notes = arrange_xml_head(path)
                _events, pickup = score_events(
                    substitute_steps(steps), head.beats_per_bar, True, head.beat_type
                )
                self.assertEqual(pickup, 3.0)

    def test_a_repeat_with_two_endings_is_committed(self):
        head = load_musicxml(RAINY_DAY)
        self.assertEqual(head.bars, (1, 13))
        self.assertEqual(
            {(marker.kind, marker.numbers) for marker in head.markers},
            {
                ("repeat_start", ()),
                ("ending_start", (1,)),
                ("ending_stop", (1,)),
                ("repeat_end", ()),
                ("ending_start", (2,)),
                ("ending_stop", (2,)),
            },
        )

    def test_the_grouped_metres_are_committed(self):
        """The three channels a score states a grouping through, one fixture each.

        5/4 writes `3+2`; 7/4 and 12/8 state theirs by beaming. A regenerated
        fixture that loses the direction or the beams would still parse, so this is
        the feature the corpus exists to keep.
        """
        expected = {
            FIVE_FOUR: ((5, 4), (3, 2), "text"),
            SEVEN_FOUR: ((7, 4), (2, 2, 3), "beams"),
            TWELVE_EIGHT: ((12, 8), (4, 4, 4), "beams"),
        }
        for path, (metre, grouping, source) in expected.items():
            with self.subTest(fixture=os.path.basename(path)):
                head = load_musicxml(path)
                self.assertEqual((head.beats_per_bar, head.beat_type), metre)
                self.assertEqual((head.grouping, head.grouping_source), (grouping, source))

    def test_the_triplet_head_still_needs_the_whole_lattice(self):
        head = load_musicxml(I_WAS_DOING_ALL_RIGHT)
        self.assertTrue(any(note.tuplet for note in head.notes))
        ticks = [round((note.beat - 1.0) * 24) for note in head.notes]
        self.assertEqual(reduce(gcd, ticks, 0), 1)

    def test_a_tab_part_beside_a_notation_part_is_committed(self):
        head = load_musicxml(TENOR_MADNESS)
        self.assertEqual(head.part, "Synthetic Tab Export")
        self.assertTrue(any("chord group" in line for line in head.skipped))

    def test_a_chords_only_head_is_committed(self):
        head = load_musicxml(CHORDS_ONLY)
        self.assertEqual(head.notes, [])
        self.assertEqual(len(head.chords), 6)

    def test_the_slash_and_degree_chords_are_committed(self):
        head = load_musicxml(RAINY_DAY)
        chords = {note.chord for note in head.notes}
        self.assertIn("Gmaj9", chords)
        self.assertIn("E7b5", chords)
        self.assertTrue(any(note.bass == "F#" for note in head.notes))

    def test_the_retained_score_still_carries_its_nc_bar(self):
        head = load_musicxml(TROUBLE_IN_MIND)
        self.assertTrue(any(note.chord == "NC" for note in head.notes))

    def test_no_synthetic_fixture_carries_a_lyric(self):
        for name in fixture_scores.documents():
            with self.subTest(fixture=name):
                head = load_musicxml(os.path.join(DATA, name))
                self.assertFalse(any(note.lyrics for note in head.notes))


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
